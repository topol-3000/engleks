RENDER_HEADER = (
    "# Generated by engleks-render-env from deploy/prod.env and Infisical. "
    "Do not edit; changes are lost on the next deploy."
)


def rendered_env(tag: str, secrets: dict[str, str] = DEFAULT_SECRETS) -> str:
    """The exact text engleks-render-env writes for the test prod.env and secrets.txt."""
    config = [line for line in TEST_PROD_ENV.splitlines() if line and not line.startswith("#")]
    secret_lines = "".join(f"{n}={secrets[n]}\n" for n in SECRET_NAMES)
    digest = hashlib.sha256(secret_lines.encode()).hexdigest()
    return (
        "\n".join([RENDER_HEADER, *config])
        + "\n"
        + secret_lines
        + f"ENGLEKS_TAG={tag}\nENGLEKS_SECRETS_HASH={digest}\n"
    )


DEFAULT_ENV = rendered_env(PREV)

STUB = r"""#!/usr/bin/env bash
name=$(basename "$0"); line="$name $*"
tag=$(sed -n 's/^ENGLEKS_TAG=//p' "$ENGLEKS_DIR/.env" 2>/dev/null | tail -n1)
extra=""
if [[ $name == restic && -n ${STUB_LS-} ]]; then
  extra=" [$(ls "$STUB_LS" | sort | xargs)]"
fi
echo "$line @$tag$extra" >> "$STUB_LOG"
if [[ $name == curl ]]; then
  for arg in "$@"; do
    if [[ $arg == @* && -r ${arg#@} ]]; then
      printf '>>> %s\n%s\n' "$line" "$(cat "${arg#@}")" >> "$STUB_INPUT_LOG"
    fi
  done
elif [[ $line == "docker compose exec -T"* ]]; then
  printf '>>> %s\n%s\n' "$line" "$(cat)" >> "$STUB_INPUT_LOG"
fi
if [[ -n ${STUB_FAIL-} && $line =~ $STUB_FAIL
      && ( -z ${STUB_FAIL_TAG-} || $tag == "${STUB_FAIL_TAG}" ) ]]; then
  exit "${STUB_FAIL_CODE:-1}"
fi
case $line in
  curl*universal-auth/login*) cat "$STUB_INFISICAL/login.json" ;;
  curl*/secrets*) cat "$STUB_INFISICAL/secrets.json" ;;
  "docker image ls"*) [[ -n ${STUB_IMAGES-} ]] && printf '%s\n' $STUB_IMAGES ;;
  *pg_dump*) echo dump ;;
  *generate_key.py*) echo "API_LLM_API_KEY=sk-generated" ;;
  "git rev-parse HEAD") echo "${STUB_HEAD-}" ;;
esac
exit 0
"""


@dataclass
class Server:
    root: Path
    backups: Path
    log: Path
    base_env: dict[str, str]
    infisical: Path
    credentials: Path
    input_log: Path

    @property
    def env_file(self) -> Path:
        return self.root / ".env"

    @property
    def lock(self) -> Path:
        return self.root / ".deploy.lock"

    def write_env(self, text: str) -> None:
        self.env_file.write_text(text)
        self.env_file.chmod(0o600)

    def env_text(self) -> str:
        return self.env_file.read_text()

    def tag(self) -> str | None:
        tags = [
            line.removeprefix("ENGLEKS_TAG=")
            for line in self.env_text().splitlines()
            if line.startswith("ENGLEKS_TAG=")
        ]
        return tags[-1] if tags else None

    def set_secrets(self, secrets: dict[str, str], hidden: tuple[str, ...] = ()) -> None:
        """Sets what the fake Infisical returns for the secrets of the environment.

        HIDDEN names the secrets the identity can list but not read: Infisical flags them
        with secretValueHidden and masks the value."""
        body = {
            "secrets": [
                {"secretKey": k, "secretValue": v}
                | ({"secretValueHidden": True} if k in hidden else {})
                for k, v in secrets.items()
            ],
            "imports": [],
        }
        (self.infisical / "secrets.json").write_text(json.dumps(body))

    def inputs(self) -> str:
        """What curl read from @files and `docker compose exec -T` read from stdin."""
        return self.input_log.read_text() if self.input_log.exists() else ""

    def calls(self) -> list[str]:
        return self.log.read_text().splitlines() if self.log.exists() else []

    def run(
        self, script: str, *args: str, input: str | None = None, **env: str | None
    ) -> subprocess.CompletedProcess[str]:
        full_env = dict(self.base_env)
        for key, value in env.items():
            if value is None:
                full_env.pop(key, None)
            else:
                full_env[key] = value
        return subprocess.run(
            ["bash", str(SCRIPTS / script), *args],
            cwd=self.root,
            env=full_env,
            input=input,
            stdin=subprocess.DEVNULL if input is None else None,
            capture_output=True,
            text=True,
            timeout=60,
            check=False,
        )


@pytest.fixture
def server(tmp_path: Path) -> Server:
    root = tmp_path / "engleks"
    backups = tmp_path / "backups"
    bin_dir = tmp_path / "bin"
    infisical = tmp_path / "infisical"
    for d in (root, backups, bin_dir, infisical, root / "deploy"):
        d.mkdir()
    real_jq = shutil.which("jq")
    if real_jq is None:
        pytest.fail("jq is required for deploy/tests (apt-get install jq)")
    stub = bin_dir / "stub"
    stub.write_text(STUB)
    stub.chmod(stub.stat().st_mode | stat.S_IXUSR)
    for name in ("git", "docker", "restic", "curl"):
        (bin_dir / name).symlink_to(stub)
    (bin_dir / "engleks-render-env").symlink_to(SCRIPTS / "engleks-render-env")
    jq = bin_dir / "jq"
    jq.write_text(f'#!/usr/bin/env bash\necho "jq $*" >> "$STUB_LOG"\nexec {real_jq} "$@"\n')
    jq.chmod(jq.stat().st_mode | stat.S_IXUSR)
    log = tmp_path / "calls.log"
    input_log = tmp_path / "inputs.log"
    credentials = tmp_path / "infisical-credentials"
    credentials.write_text("".join(f"{k}={v}\n" for k, v in CREDENTIALS.items()))
    credentials.chmod(0o600)
    (root / "deploy" / "prod.env").write_text(TEST_PROD_ENV)
    (root / "deploy" / "secrets.txt").write_text(TEST_SECRETS_TXT)
    (infisical / "login.json").write_text(json.dumps(LOGIN_RESPONSE))
    base_env = {
        "PATH": f"{bin_dir}:/usr/bin:/bin",
        "HOME": str(tmp_path),
        "ENGLEKS_DIR": str(root),
        "BACKUP_DIR": str(backups),
        "STUB_LOG": str(log),
        "STUB_INPUT_LOG": str(input_log),
        "STUB_INFISICAL": str(infisical),
        "ENGLEKS_INFISICAL_CREDENTIALS": str(credentials),
        "ENGLEKS_LOCK_TIMEOUT": "1",
    }
    s = Server(
        root=root,
        backups=backups,
        log=log,
        base_env=base_env,
        infisical=infisical,
        credentials=credentials,
        input_log=input_log,
    )
    s.set_secrets(DEFAULT_SECRETS)
    s.write_env(DEFAULT_ENV)
    return s


@pytest.fixture
def held_lock(server: Server) -> Iterator[None]:
    """Holds the deploy lock, as a running deploy would."""
    holder = subprocess.Popen(["flock", str(server.lock), "sleep", "5"])
    try:
        # Wait until the holder has the lock: a non-blocking flock then fails.
        for _ in range(100):
            probe = subprocess.run(["flock", "-n", str(server.lock), "true"], check=False)
            if probe.returncode != 0:
                break
            subprocess.run(["sleep", "0.05"], check=True)
        else:
            pytest.fail("lock holder never took the lock")
        yield
    finally:
        holder.kill()
        holder.wait()


def mode(path: Path) -> int:
    return stat.S_IMODE(os.stat(path).st_mode)
