"""Harness for the server scripts in deploy/server.

Each test gets a fake server: a checkout directory (ENGLEKS_DIR) with a .env, a backup
staging directory (BACKUP_DIR) and a bin directory whose git, docker, restic and curl are
one stub script. The stub logs every call with the ENGLEKS_TAG in .env at that moment,
fails calls matching STUB_FAIL (with STUB_FAIL_CODE, optionally only while the tag is
STUB_FAIL_TAG) and prints canned output for the few calls whose output the scripts read.
It also records what curl reads from @files and what `docker compose exec -T` reads from
stdin in STUB_INPUT_LOG, so tests can check what a script sends without it being in argv.
The fake checkout holds deploy/prod.env and deploy/secrets.txt, and the fake Infisical is
two canned JSON files that the stub's curl prints. jq is the real one, behind a wrapper
that logs its arguments.
"""

